#!/bin/bash
################################################################################
# Point Traefik's api.smholdings.gr routes at one colour, and prove Traefik
# took it -- the stefanos form of the nginx upstream block in deploy.sh.
#
#   bash deploy-traefik-route.sh stefanos-blue|stefanos-green
#
# Called by /root/deploy.sh after the new colour's health check passes, once
# the edge is Traefik (deploy.sh keeps its nginx block for when it is not --
# it checks for /etc/stefanos/traefik/dynamic first). Exits non-zero, leaving
# the previous file in force, when Traefik does not confirm the change; the
# deploy must then abort before it stops the old colour.
#
# What it writes, /etc/stefanos/traefik/dynamic/api.yml, is hot-reloaded by
# the file provider: no reload, no restart, and Traefik's API (loopback only)
# reports what was actually loaded -- a router with a broken rule or a missing
# middleware shows up there as disabled and nowhere else.
################################################################################

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

if [ "$#" -lt 1 ]; then
    echo "Usage: $0 <container>" >&2
    exit 2
fi
CONTAINER=$1

TRAEFIK_DIR=${TRAEFIK_DIR:-/etc/stefanos/traefik}
TRAEFIK_API=${TRAEFIK_API:-http://127.0.0.1:8099}
TRAEFIK_HTTPS_PORT=${TRAEFIK_HTTPS_PORT:-443}
API_DOMAIN=${API_DOMAIN:-api.smholdings.gr}
APP_PORT=${APP_PORT:-3001}
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

TARGET="$TRAEFIK_DIR/dynamic/api.yml"
UPSTREAM="http://$CONTAINER:$APP_PORT"

mkdir -p "$TRAEFIK_DIR/dynamic"

# The host-wide edge rules, reinstalled on every deploy -- same reason the
# nginx vhost was rewritten: a file that only exists on the box is a file no
# rebuild brings back. Installed first because api.yml names its middlewares.
if [ -f "$SCRIPT_DIR/docker/traefik/edge.yml" ]; then
    install -m 0644 "$SCRIPT_DIR/docker/traefik/edge.yml" "$TRAEFIK_DIR/dynamic/00-edge.yml.tmp"
    mv "$TRAEFIK_DIR/dynamic/00-edge.yml.tmp" "$TRAEFIK_DIR/dynamic/00-edge.yml"
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

cat > "$TMP" <<EOF
# Generated by stefanos-backend/deploy-traefik-route.sh on $(date -u '+%Y-%m-%d %H:%M:%S UTC').
# DO NOT EDIT BY HAND -- the next deploy overwrites it. Change the script.
#
# Live colour: $CONTAINER

http:
  services:
    # Traefik keeps a keepalive pool to the app by default and passes the
    # client's Host header through. healthCheck pulls a wedged colour out of
    # rotation on its own, before the deploy script would notice.
    stefanos:
      loadBalancer:
        servers:
          - url: "$UPSTREAM"
        healthCheck:
          path: /api/health
          interval: 10s
          timeout: 3s

  routers:
    # /api/auth/* (login, refresh, password): the tight limit -- a security
    # control, not a capacity one.
    stefanos-auth:
      entryPoints: [websecure]
      rule: "Host(\`$API_DOMAIN\`) && PathPrefix(\`/api/auth\`)"
      priority: 900
      middlewares: [st-ratelimit-auth@file, st-inflight@file, st-compress@file, st-secure-headers@file]
      service: stefanos
      tls:
        certResolver: letsencrypt

    # Everything else on the API host.
    stefanos-api:
      entryPoints: [websecure]
      rule: "Host(\`$API_DOMAIN\`)"
      priority: 100
      middlewares: [st-ratelimit-api@file, st-inflight@file, st-compress@file, st-secure-headers@file]
      service: stefanos
      tls:
        certResolver: letsencrypt
EOF

# The previous file, kept until this one is proven: if Traefik does not load
# the new routes it goes back, so a failed deploy leaves the old colour
# serving rather than a route to nowhere.
cp -p "$TARGET" "$TARGET.prev" 2>/dev/null || true
restore_previous() {
    if [ -f "$TARGET.prev" ]; then
        mv "$TARGET.prev" "$TARGET"
        echo -e "${YELLOW}  Previous $TARGET restored${NC}"
    fi
}

# Atomic: Traefik watches the directory and must never read a half-written
# file. The .tmp/.prev extensions are ones the file provider ignores.
install -m 0644 "$TMP" "$TARGET.tmp"
mv "$TARGET.tmp" "$TARGET"
echo -e "${GREEN}  ✓ $TARGET written ($CONTAINER via $UPSTREAM)${NC}"

if [ "${TRAEFIK_ROUTE_VERIFY:-1}" = 0 ]; then
    exit 0
fi

traefik_has_loaded() {
    local svc router
    svc=$(curl -sf --max-time 3 "$TRAEFIK_API/api/http/services/stefanos@file" 2>/dev/null) || return 1
    router=$(curl -sf --max-time 3 "$TRAEFIK_API/api/http/routers/stefanos-api@file" 2>/dev/null) || return 1
    echo "$svc" | grep -qF "\"url\":\"$UPSTREAM\"" || return 1
    echo "$router" | grep -q '"status":"enabled"' || return 1
}

loaded=0
for _ in $(seq 1 20); do
    if traefik_has_loaded; then
        loaded=1
        break
    fi
    sleep 1
done
if [ "$loaded" -ne 1 ]; then
    echo -e "${RED}✗ Traefik did not load api.yml with $UPSTREAM within 20s${NC}"
    echo -e "${RED}  Check: tail -20 /etc/stefanos/traefik/logs/traefik.log${NC}"
    tail -5 "$TRAEFIK_DIR/logs/traefik.log" 2>&1 | sed 's/^/    /' || true
    restore_previous
    exit 1
fi

# Then a real request through it: 502/504/000 mean nothing answered;
# anything else (401 included) means the app did. --resolve so the TLS
# server name is the API's.
status=""
for _ in 1 2 3 4 5; do
    status=$(curl -sk -o /dev/null -w '%{http_code}' --max-time 10 \
        --resolve "$API_DOMAIN:$TRAEFIK_HTTPS_PORT:127.0.0.1" \
        "https://$API_DOMAIN:$TRAEFIK_HTTPS_PORT/api/health" 2>/dev/null || true)
    case "$status" in
        502|503|504|000|"") sleep 2 ;;
        *)
            echo -e "${GREEN}  ✓ Traefik serves $API_DOMAIN from $CONTAINER (HTTP $status)${NC}"
            rm -f "$TARGET.prev"
            exit 0
            ;;
    esac
done
echo -e "${RED}✗ Traefik loaded the route but the API does not answer through it (last: ${status:-none})${NC}"
restore_previous
exit 1
